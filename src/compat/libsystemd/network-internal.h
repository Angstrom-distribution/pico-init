/*
 * Shared plumbing for the sd-network family: the test-root prefix every
 * absolute path goes through, and the provenance check network-resolv.c
 * and its test share.
 */

#pragma once

#include <stddef.h>

/*
 * Every real path this family reads (netd.h's NETD_RESOLV_CONF,
 * NETD_LEASE_DIR, and their parent directories) is an absolute host path a
 * test cannot write to. `prefix` goes in front of all of them, "" in
 * production so behaviour is byte-for-byte the real absolute path; a test
 * points it at a scratch tree instead. Test-only: production code never
 * calls the setter, mirroring device-internal.h's device_sys_root().
 */
void network_set_root_for_tests(const char *prefix);

/* buf = "<root prefix><abs_path>". Truncation is reported the same way
 * every other fixed-buffer path build in this project is: the caller's
 * own snprintf-return-value check, since this is itself just one. */
int network_path(char *buf, size_t size, const char *abs_path);

/*
 * The sentinel netd-resolv.c writes as the first line of the file
 * (netd-resolv.c's own write_atomic() call), and the only thing that
 * proves this /etc/resolv.conf was written by netd rather than by
 * something else entirely -- accepting an unmarked file would mean
 * attributing arbitrary data to the network manager. Shared between
 * sd_network_get_dns() and sd_network_get_search_domains(), which parse
 * the same file under the same rule.
 */
#define NETD_RESOLV_SENTINEL "# generated by netd -- do not edit"

/*
 * Read netd's resolv.conf, gated on NETD_RESOLV_SENTINEL as the file's
 * first line. -ENODATA when the file is absent or unmarked (network-
 * resolv.c's whole point); 0 on success with *ret_lines a NULL-terminated
 * malloc'd array of malloc'd lines (nameserver/search lines only, in file
 * order), or -errno. Caller frees with pico_strv_free()-shaped ownership.
 */
int network_resolv_read(char ***ret_lines);
