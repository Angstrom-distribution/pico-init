/* Shared by the sd-network sources: the test-root path prefix and the
 * resolv.conf provenance check. */

#pragma once

#include <stddef.h>

/*
 * Every path read here (netd.h's NETD_RESOLV_CONF, NETD_LEASE_DIR and their
 * parent directories) is an absolute host path a test cannot write to.
 * `prefix` is prepended to all of them: "" in production, a scratch tree in
 * tests. Test-only, like device-internal.h's device_sys_root().
 */
void network_set_root_for_tests(const char *prefix);

/* buf = "<root prefix><abs_path>"; -ENAMETOOLONG on truncation. */
int network_path(char *buf, size_t size, const char *abs_path);

/*
 * First line netd-resolv.c writes to /etc/resolv.conf. It is the only proof
 * that netd wrote the file; an unmarked file is not attributed to netd.
 */
#define NETD_RESOLV_SENTINEL "# generated by netd -- do not edit"

/*
 * Read netd's resolv.conf, gated on NETD_RESOLV_SENTINEL as the file's
 * first line. -ENODATA when the file is absent or unmarked; 0 on success
 * with *ret_lines a NULL-terminated malloc'd array of malloc'd lines
 * (nameserver/search lines only, in file order), or -errno. The caller
 * frees each line and the array.
 */
int network_resolv_read(char ***ret_lines);
