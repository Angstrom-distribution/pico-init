/*
 * sd-network's resolv.conf family against a fixture file, the provenance
 * gate, the always-empty route_domains, the ntp getter, a sample of the
 * -EOPNOTSUPP state getters plus the ifindex validation they share, and
 * link_get_stat against a lease file.
 */

#include "sd-network.h"

#include <errno.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

#include "../../test-util.h"
#include "network-internal.h"

static char *g_tmp;

static void setup(void) {
        g_tmp = test_tmpdir_new();
        ASSERT_TRUE(g_tmp != NULL);
        network_set_root_for_tests(g_tmp);
}

static void teardown(void) {
        network_set_root_for_tests(NULL);
        test_rm_rf(g_tmp);
        free(g_tmp);
}

static void test_dns_and_search_no_file(void) {
        char **ret = NULL;

        setup();

        ASSERT_EQ_INT(sd_network_get_dns(&ret), -ENODATA); /* file does not exist yet */
        ASSERT_EQ_INT(sd_network_get_search_domains(&ret), -ENODATA);
        ASSERT_EQ_INT(sd_network_get_dns(NULL), -EINVAL);

        teardown();
}

static void test_dns_wrong_provenance(void) {
        char **ret = NULL;

        setup();
        ASSERT_EQ_INT(test_mkdir(g_tmp, "etc"), 0);
        ASSERT_EQ_INT(test_write_file(g_tmp, "etc/resolv.conf", "nameserver 1.2.3.4\n"), 0);

        /* No sentinel first line: not attributable to netd. */
        ASSERT_EQ_INT(sd_network_get_dns(&ret), -ENODATA);

        teardown();
}

static void test_dns_and_search_real_file(void) {
        char **ret = NULL;
        int n;

        setup();
        ASSERT_EQ_INT(test_mkdir(g_tmp, "etc"), 0);
        ASSERT_EQ_INT(test_write_file(g_tmp,
                                      "etc/resolv.conf",
                                      "# generated by netd -- do not edit\n"
                                      "nameserver 192.0.2.1\n"
                                      "nameserver 192.0.2.2\n"
                                      "search example.com\n"),
                      0);

        ASSERT_EQ_INT(sd_network_get_dns(&ret), 0);
        n = 0;
        for (char **p = ret; p && *p; p++, n++)
                ;
        ASSERT_EQ_INT(n, 2);
        ASSERT_STREQ(ret[0], "192.0.2.1");
        ASSERT_STREQ(ret[1], "192.0.2.2");
        for (char **p = ret; p && *p; p++)
                free(*p);
        free(ret);
        ret = NULL;

        ASSERT_EQ_INT(sd_network_get_search_domains(&ret), 0);
        ASSERT_TRUE(ret != NULL);
        ASSERT_STREQ(ret[0], "example.com");
        ASSERT_TRUE(ret[1] == NULL);
        for (char **p = ret; p && *p; p++)
                free(*p);
        free(ret);

        teardown();
}

static void test_dns_empty_when_only_sentinel(void) {
        char **ret = (char **) 0x1; /* poison: must be overwritten to NULL */

        setup();
        ASSERT_EQ_INT(test_mkdir(g_tmp, "etc"), 0);
        ASSERT_EQ_INT(test_write_file(g_tmp, "etc/resolv.conf", "# generated by netd -- do not edit\n"), 0);

        ASSERT_EQ_INT(sd_network_get_dns(&ret), 0);
        ASSERT_TRUE(ret == NULL); /* the header's own NULL-for-empty convention */

        teardown();
}

static void test_route_domains_and_ntp(void) {
        char **ret = NULL;

        ASSERT_EQ_INT(sd_network_get_route_domains(&ret), 0);
        ASSERT_TRUE(ret == NULL);
        ASSERT_EQ_INT(sd_network_get_route_domains(NULL), -EINVAL);

        ASSERT_EQ_INT(sd_network_get_ntp(&ret), -EOPNOTSUPP);
}

static void test_state_stub_family(void) {
        char *v = NULL;

        /* Global: no ret is -EINVAL before anything else. */
        ASSERT_EQ_INT(sd_network_get_operational_state(NULL), -EINVAL);
        ASSERT_EQ_INT(sd_network_get_operational_state(&v), -EOPNOTSUPP);

        /* Per-link: bad ifindex always wins over the -EOPNOTSUPP. */
        ASSERT_EQ_INT(sd_network_link_get_operational_state(0, &v), -EINVAL);
        ASSERT_EQ_INT(sd_network_link_get_operational_state(-1, &v), -EINVAL);
        ASSERT_EQ_INT(sd_network_link_get_operational_state(1, &v), -EOPNOTSUPP);

        /* A getter for a directive netd lacks, same shape. */
        ASSERT_EQ_INT(sd_network_link_get_activation_policy(0, &v), -EINVAL);
        ASSERT_EQ_INT(sd_network_link_get_activation_policy(1, &v), -EOPNOTSUPP);

        /* A direct-int-return getter (no `ret` out-param at all). */
        ASSERT_EQ_INT(sd_network_link_get_required_for_online(0), -EINVAL);
        ASSERT_EQ_INT(sd_network_link_get_required_for_online(1), -EOPNOTSUPP);
        ASSERT_EQ_INT(sd_network_link_get_dns_default_route(1), -EOPNOTSUPP);
}

static void test_link_get_stat(void) {
        struct stat st;

        setup();

        ASSERT_EQ_INT(sd_network_link_get_stat(1, &st), -ENOENT); /* no lease file yet */
        ASSERT_EQ_INT(sd_network_link_get_stat(0, &st), -EINVAL);
        ASSERT_EQ_INT(sd_network_link_get_stat(1, NULL), -EINVAL);

        ASSERT_EQ_INT(test_mkdir(g_tmp, "run"), 0);
        ASSERT_EQ_INT(test_mkdir(g_tmp, "run/netd"), 0);
        ASSERT_EQ_INT(test_mkdir(g_tmp, "run/netd/leases"), 0);
        ASSERT_EQ_INT(test_write_file(g_tmp, "run/netd/leases/1", "ADDRESS=192.0.2.9\n"), 0);

        ASSERT_EQ_INT(sd_network_link_get_stat(1, &st), 0);
        ASSERT_TRUE(st.st_size > 0);

        teardown();
}

int main(void) {
        test_dns_and_search_no_file();
        test_dns_wrong_provenance();
        test_dns_and_search_real_file();
        test_dns_empty_when_only_sentinel();
        test_route_domains_and_ntp();
        test_state_stub_family();
        test_link_get_stat();

        printf("test-sd-network: OK\n");
        return 0;
}
