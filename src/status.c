/*
 * The console status channel. See status.h for why this is not pico_log().
 */

#include "status.h"

#include <fcntl.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#include "os-release.h"
#include "util.h"

/* Disabled until status_enable(); see status.h for why that is opt-in. */
static int status_fd = -1;
static bool status_color = false;

/*
 * Colour unless the console says it is a dumb terminal. That is the whole of
 * systemd's own console rule: dev_console_colors_enabled()
 * (src/basic/terminal-util.c) ends in `return !streq_ptr(s, "dumb")`, so an
 * unset TERM is colourable and only the literal "dumb" is not.
 *
 * Its two earlier checks, $SYSTEMD_COLORS and $NO_COLOR, are deliberately not
 * carried over: PID 1 here inherits no environment worth the name and has no
 * kernel-command-line parser to read one from, so they would be knobs nothing
 * can turn. A terminfo capability probe would be worse still -- the console
 * this writes to is a kernel VT or a serial line, and both take SGR.
 */
static bool console_colors_enabled(void) {
        const char *term = getenv("TERM");

        return !term || strcmp(term, "dumb") != 0;
}

void status_enable(void) {
        int fd;

        if (status_fd >= 0)
                return;

        fd = open("/dev/console", O_WRONLY | O_NOCTTY | O_CLOEXEC);
        status_fd = fd >= 0 ? fd : STDOUT_FILENO;
        status_color = console_colors_enabled();
}

/* One write() for one line, for the reason pico_log_internal() spells out:
 * a line-oriented destination should not have to reassemble what was meant
 * to be a single record. */
static void status_write(const char *buf, size_t n) {
        if (status_fd < 0 || n == 0)
                return;

        /* Not `(void) write(...)`: a void cast does not suppress
         * warn_unused_result -- see pico_log_internal(). */
        if (write(status_fd, buf, n) < 0) {
                /* Nothing useful to do here: this is the console. */
        }
}

size_t status_format_line(char *buf, size_t size, const char *word, const char *color, const char *text) {
        int n;

        if (!buf || size < 2) {
                if (buf && size > 0)
                        buf[0] = '\0';
                return 0;
        }

        if (word)
                n = snprintf(buf, size, "[%s%s%s] %s\n", color ? color : "", word, color ? ANSI_NORMAL : "", text);
        else
                n = snprintf(buf, size, "%s\n", text);

        if (n < 0) {
                buf[0] = '\0';
                return 0;
        }

        /* Truncated. Give the line its newline back rather than emitting a
         * fragment that the next one continues on the same console row. */
        if ((size_t) n >= size) {
                buf[size - 2] = '\n';
                return size - 1;
        }

        return (size_t) n;
}

void status_printf(const char *word, const char *color, const char *format, ...) {
        char text[512], line[1024];
        va_list ap;
        size_t n;

        if (status_fd < 0)
                return;

        va_start(ap, format);
        (void) vsnprintf(text, sizeof(text), format, ap);
        va_end(ap);

        n = status_format_line(line, sizeof(line), word, status_color ? color : NULL, text);
        status_write(line, n);
}

/*
 * ANSI_COLOR= is spliced straight into an SGR sequence, so only the bytes
 * that can legally appear in one are accepted. os-release is generated by an
 * image build, a broken build can put anything in it, and "anything" spliced
 * between ESC[ and m is a terminal reprogrammed by a malformed file.
 */
static bool ansi_color_is_valid(const char *s) {
        return s && s[0] != '\0' && s[strspn(s, "0123456789;")] == '\0';
}

size_t status_welcome_line(char *buf, size_t size, const char *path, bool color) {
        char *pretty = NULL, *name = NULL, *ansi_color = NULL;
        const char *label, *sgr;
        char text[512];

        if (!path)
                path = OS_RELEASE_PATH;

        /*
         * PRETTY_NAME, then NAME, then "Linux" -- os_release_pretty_name()'s
         * fallback chain in systemd, and what turns a missing file, a missing
         * key and an empty value alike into a sensible greeting rather than
         * "Welcome to !". NAME is only read when it is actually needed, so
         * the common case reads the file twice, not three times; a multi-key
         * lookup would be more machinery than it saves on a dozen-line file
         * read once per boot.
         */
        (void) os_release_get(path, "PRETTY_NAME", &pretty);
        if (!pretty || pretty[0] == '\0')
                (void) os_release_get(path, "NAME", &name);

        if (pretty && pretty[0] != '\0')
                label = pretty;
        else if (name && name[0] != '\0')
                label = name;
        else
                label = "Linux";

        /*
         * Byte for byte systemd's own greeting (os_release_status(),
         * src/core/main.c):
         *
         *   "\n" ANSI_HIGHLIGHT "Welcome to " ANSI_NORMAL "%s" ANSI_NORMAL
         *   ANSI_HIGHLIGHT "!" ANSI_NORMAL "\n"
         *
         * with the name itself wrapped in whatever SGR parameters os-release
         * names in ANSI_COLOR=, defaulting to "1" (bold) when it names none.
         * The blank line either side is upstream's too: it is what lifts the
         * greeting out of the kernel's own boot spew.
         */
        if (color) {
                (void) os_release_get(path, "ANSI_COLOR", &ansi_color);
                sgr = ansi_color_is_valid(ansi_color) ? ansi_color : "1";

                (void) snprintf(text,
                                sizeof(text),
                                "\n" ANSI_HIGHLIGHT "Welcome to " ANSI_NORMAL
                                "\x1B[%sm%s" ANSI_NORMAL ANSI_HIGHLIGHT "!" ANSI_NORMAL "\n",
                                sgr,
                                label);
        } else
                (void) snprintf(text, sizeof(text), "\nWelcome to %s!\n", label);

        pretty = pico_mfree(pretty);
        name = pico_mfree(name);
        ansi_color = pico_mfree(ansi_color);

        return status_format_line(buf, size, NULL, NULL, text);
}

void status_welcome(const char *path) {
        char line[1024];
        size_t n;

        if (status_fd < 0)
                return;

        n = status_welcome_line(line, sizeof(line), path, status_color);
        status_write(line, n);
}
