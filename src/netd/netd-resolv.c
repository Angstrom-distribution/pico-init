/*
 * /etc/resolv.conf. See netd-resolv.h for the rules.
 *
 * A full rebuild from every link's static DNS= plus, where UseDNS=
 * allows it, the link's lease's option 6 -- and the lease's domainname
 * (option 15) as a single `search` line. There is no static equivalent of
 * the domain (netd-network.h's Network has no Domain= field), so `search`
 * only ever comes from DHCP.
 */

#include "netd-resolv.h"

#include <arpa/inet.h>
#include <errno.h>
#include <fcntl.h>
#include <limits.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

#include "../util.h"
#include "dhcp/dhcp-lease-internal.h"
#include "netd-link.h"
#include "netd-network.h"
#include "netd.h"

/* Add `a` to `servers` if it is not already present and there is room.
 * Silently drops anything past NETD_RESOLV_MAX_NAMESERVERS -- glibc itself
 * reads no more than that, so a fourth entry would be misleading, not
 * generous. */
static void add_nameserver(struct in_addr *servers, size_t *n, const struct in_addr *a) {
        if (*n >= NETD_RESOLV_MAX_NAMESERVERS)
                return;

        for (size_t i = 0; i < *n; i++)
                if (servers[i].s_addr == a->s_addr)
                        return;

        servers[(*n)++] = *a;
}

/* Atomic tmp+rename over a fixed suffix -- netd is single-threaded and this
 * runs to completion within one epoll iteration, so there is no concurrent
 * writer to race (same reasoning as netd-time.c's atomic_symlink()). */
static int write_atomic(const char *path, const char *content, size_t len) {
        char tmp[PATH_MAX];
        int fd, len_snp, r;
        ssize_t written;

        len_snp = snprintf(tmp, sizeof(tmp), "%s.netd-tmp", path);
        if (len_snp < 0 || (size_t) len_snp >= sizeof(tmp))
                return -ENAMETOOLONG;

        fd = open(tmp, O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0644);
        if (fd < 0)
                return -errno;

        written = write(fd, content, len);
        if (written < 0 || (size_t) written != len) {
                r = written < 0 ? -errno : -EIO;
                (void) close(fd);
                (void) unlink(tmp);
                return r;
        }

        if (close(fd) < 0) {
                r = -errno;
                (void) unlink(tmp);
                return r;
        }

        if (rename(tmp, path) < 0) {
                r = -errno;
                (void) unlink(tmp);
                return r;
        }

        return 0;
}

int netd_resolv_write(Netd *n) {
        struct in_addr servers[NETD_RESOLV_MAX_NAMESERVERS];
        size_t n_servers = 0;
        const char *domain = NULL;
        char buf[4096];
        size_t off = 0;
        int written;

        if (!n || !n->resolv_conf)
                return -EINVAL;

        for (size_t i = 0; i < n->n_links; i++) {
                Link *l = n->links[i];
                Network *nw = l->network;

                if (!nw)
                        continue;

                for (size_t j = 0; j < nw->n_dns; j++)
                        add_nameserver(servers, &n_servers, &nw->dns[j]);

                if (nw->dhcp_use_dns && l->lease) {
                        const struct in_addr *dns;
                        int r = dhcp_lease_get_dns(l->lease, &dns);

                        if (r > 0)
                                for (int k = 0; k < r; k++)
                                        add_nameserver(servers, &n_servers, &dns[k]);
                }

                if (!domain && l->lease) {
                        const char *d;

                        if (dhcp_lease_get_domainname(l->lease, &d) >= 0)
                                domain = d;
                }
        }

        if (n_servers == 0 && !domain) {
                /* Nothing to write: never blank out a working file just
                 * because the last link lost its lease (netd-resolv.h). */
                return 1;
        }

        written = snprintf(buf + off, sizeof(buf) - off, "# generated by netd -- do not edit\n");
        if (written > 0 && (size_t) written < sizeof(buf) - off)
                off += (size_t) written;

        for (size_t i = 0; i < n_servers; i++) {
                char ip[INET_ADDRSTRLEN];

                if (!inet_ntop(AF_INET, &servers[i], ip, sizeof(ip)))
                        continue;

                written = snprintf(buf + off, sizeof(buf) - off, "nameserver %s\n", ip);
                if (written < 0 || (size_t) written >= sizeof(buf) - off)
                        break;
                off += (size_t) written;
        }

        if (domain) {
                written = snprintf(buf + off, sizeof(buf) - off, "search %s\n", domain);
                if (written > 0 && (size_t) written < sizeof(buf) - off)
                        off += (size_t) written;
        }

        return write_atomic(n->resolv_conf, buf, off);
}
